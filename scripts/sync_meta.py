def outputs(m: dict) -> dict[Path, Callable[[dict, str | None], str]]:
    """OUTPUTS plus one page per file in brand/docs (home.md becomes the portal's index.md)."""
    pages = {
        DOCS / ("index.md" if src.name == "home.md" else src.name): brand_page(src)
        for src in sorted((m["brand_dir"] / "docs").glob("*.md"))
    }
    return OUTPUTS | pages


def image_copies(m: dict) -> dict[Path, bytes]:
    """Every image, byte for byte, at its fixed name in each folder that uses it."""
    return {
        folder / name: m["images"][key].read_bytes()
        for folder, keys in IMAGE_DIRS.items()
        for key in keys
        if (name := published(m, key))
    }


def output_paths(root: Path) -> list[Path]:
    """Every file `task sync` writes, for the docs' project metadata page."""
    m = load(root)
    return sorted([*outputs(m), *image_copies(m)])


