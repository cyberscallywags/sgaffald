def zensical(m: dict, text: str | None) -> str:
    project, org = m["project"], m["organisation"]
    footer = " · ".join(filter(None, [f"© {project['year']} {org['name']}", org.get("motto")]))
    text = splice(
        text or "",
        "identity",
        f"site_name = {toml_str(project['name'])}\n"
        f"site_description = {toml_str(project['description'])}\n"
        f"site_author = {toml_str(org['name'])}\n"
        f"copyright = {toml_str(footer)}\n",
    )
    social = ""
    if url := org.get("url"):
        social = (
            "[[project.extra.social]]\n"
            'icon = "lucide/globe"\n'
            f"link = {toml_str(url)}\n"
            f"name = {toml_str(org['name'])}\n"
        )
    text = splice(text, "social", social)
    images = "".join(
        f'{key} = "assets/brand/{name}"\n'
        for key, name in (("logo", published(m, "mark")), ("favicon", published(m, "favicon")))
        if name
    )
    text = splice(text, "images", images)
    text = splice(text, "palette", zensical_palette(m["palette"]["scheme"]))
    excluded = ["manual.md", "reference/python-api-sphinx.md"]
    if not include_handbook(m):
        excluded.append("handbook/")
    text = splice(text, "exclude", 'exclude_docs = """\n' + "\n".join(excluded) + '\n"""\n')
    return splice(
        text, "handbook", zensical_handbook() if include_handbook(m) else "", ("  # ", "")
    )


def include_handbook(m: dict) -> bool:
    return m.get("docs", {}).get("include_handbook", True)


def zensical_handbook() -> str:
    """The Handbook tab: its own pages first, then one section per later group."""
    (_, pages), *groups = HANDBOOK
    lines = ['  { "Handbook" = [', *(f'    "handbook/{page}.md",' for page in pages)]
    for title, group in groups:
        lines += [
            f'    {{ "{title}" = [',
            *(f'      "handbook/{p}.md",' for p in group),
            "    ] },",
        ]
    return "\n".join([*lines, "  ] },"]) + "\n"


def zensical_palette(first: str) -> str:
    """The light/dark toggle, opening in the brand's scheme."""
    entries = {
        "dark": ("slate", "lucide/sun", "Switch to light mode"),
        "light": ("default", "lucide/moon", "Switch to dark mode"),
    }
    order = ["dark", "light"] if first == "dark" else ["light", "dark"]
    return "\n".join(
        f'[[project.theme.palette]]\nscheme = "{scheme}"\n'
        f'toggle.icon = "{icon}"\ntoggle.name = "{label}"\n'
        for scheme, icon, label in (entries[name] for name in order)
    )


def brand_css(m: dict, _: str | None) -> str:
    """The docs palette as --brand-* tokens, read by template.css, zensical.css and Furo."""
    p = m["palette"]
    tokens = {
        "primary": m["primary"],
        "secondary": m["secondary"],
        "tertiary": m["tertiary"],
        "accent": p["accent"],
        "accent-rgb": ", ".join(map(str, hex_to_rgb(p["accent"]))),
        "accent-2": p["accent_2"],
        "accent-2-rgb": ", ".join(map(str, hex_to_rgb(p["accent_2"]))),
        "accent-2-light": mix(hex_to_rgb(p["accent_2"]), 255, 0.3),
        "accent-ink": p["accent_ink"],
        "accent-2-ink": p["accent_2_ink"],
        "background": p["background"],
        "background-2": blend(p["background"], p["surface"], 0.4),
        "surface": p["surface"],
        "card": p["card"],
        "border": p["border"],
        "text": p["text"],
        "text-muted": p["text_muted"],
        "text-subtle": p["text_subtle"],
        "font": m.get("font_family", DEFAULT_FONT),
        "mono": p["font_mono"],
        "gradient": "linear-gradient(90deg, var(--brand-accent), var(--brand-accent-2))",
        "glow": (
            "0 10px 15px -3px rgba(var(--brand-accent-rgb), 0.2), "
            "0 4px 6px -4px rgba(var(--brand-accent-rgb), 0.2)"
        ),
    }
    lines = "".join(f"  --brand-{name}: {value};\n" for name, value in tokens.items())
    return f"/* {NOTE} */\n:root {{\n{lines}}}\n"


def brand_extra_css(m: dict, _: str | None) -> str:
    """brand/styles/docs.css verbatim: anything the palette cannot express."""
    extra = m["brand_dir"] / "styles/docs.css"
    body = extra.read_text() if extra.exists() else "/* This brand adds no docs styles. */\n"
    return f"/* {NOTE} */\n{body}"


