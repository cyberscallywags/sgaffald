def readme(m: dict, text: str | None) -> str:
    r = repo_slug(m)
    badges = "".join(
        f"[![{label}]({image.format(r=r)})]({link.format(r=r)})\n" for label, image, link in BADGES
    )
    text = splice(text or "", "header", f"---\n\n{badges}", ("<!-- ", " -->"))
    hero = ""
    if name := published(m, "hero"):
        hero = (
            f'<p align="center">\n  <img src="docs/content/assets/brand/{name}" '
            f'alt="{m["alt"]["hero"]}" width="100%">\n</p>\n'
        )
    return splice(text, "hero", hero, ("<!-- ", " -->"))


def pyproject(m: dict, text: str | None) -> str:
    """[project] name and description, and the `<name>[extras]` self-references in the
    dependency groups. uv and hatch own everything else, the version included. The import
    package stays `app`; only the distribution is named after the slug."""
    text = text or ""
    slug = m["project"]["slug"]
    if found := re.search(r'^name = "([^"]*)"$', text, flags=re.M):
        text = text.replace(f'"{found[1]}[', f'"{slug}[')
    text = re.sub(r"^name = .*$", lambda _: f"name = {toml_str(slug)}", text, count=1, flags=re.M)
    line = f"description = {toml_str(m['project']['description'])}"
    return re.sub(r"^description = .*$", lambda _: line, text, count=1, flags=re.M)


def npm_package(m: dict, text: str | None) -> str:
    data = json.loads(text or "{}")
    data.update(
        name=f"{m['project']['slug']}-mobile",
        version=m["version"],
        author=m["organisation"]["name"],
        description=f"{m['project']['name']} mobile app (Ionic + Angular), talks to the API only",
    )
    return json_text(data)


def npm_lock(m: dict, text: str | None) -> str:
    data = json.loads(text or "{}")
    for entry in (data, data.setdefault("packages", {}).setdefault("", {})):
        entry.update(name=f"{m['project']['slug']}-mobile", version=m["version"])
    return json_text(data)


def ionic_config(m: dict, text: str | None) -> str:
    data = json.loads(text or "{}")
    data["name"] = f"{m['project']['slug']}-mobile"
    return json_text(data)


def index_html(m: dict, text: str | None) -> str:
    title = f"<title>{m['brand']['name']}</title>"
    text = re.sub(r"<title>.*?</title>", lambda _: title, text or "", count=1)
    name = published(m, "favicon")
    kind = "image/svg+xml" if name.endswith(".svg") else "image/png"
    icon = f'<link rel="icon" type="{kind}" href="assets/brand/{name}" />'
    return re.sub(r'<link rel="icon"[^>]*/>', lambda _: icon, text, count=1)


