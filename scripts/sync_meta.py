def stale(root: Path, brand: Path | None = None) -> dict[Path, str | bytes | None]:
    """Every output whose file differs from what the brand says, with its new content; None
    for a file in an image folder that the brand no longer provides."""
    m = load(root, brand)
    changes: dict[Path, str | bytes | None] = {}
    for rel, render in outputs(m).items():
        path = root / rel
        current = path.read_text() if path.exists() else None
        if (new := render(m, current)) != current:
            changes[rel] = new
    copies = image_copies(m)
    for rel, data in copies.items():
        path = root / rel
        if not path.exists() or path.read_bytes() != data:
            changes[rel] = data
    for folder in IMAGE_DIRS:
        if (root / folder).is_dir():
            for path in (root / folder).iterdir():
                if (rel := path.relative_to(root)) not in copies:
                    changes[rel] = None
    return changes


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="list stale files, write nothing")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--brand", type=Path, help="brand folder (default: <root>/brand)")
    args = parser.parse_args(argv)
    if found := problems(load(args.root, args.brand), args.root):
        for problem in found:
            print(f"brand: {problem}", file=sys.stderr)
        return 2
    changes = stale(args.root, args.brand)
    for rel, content in changes.items():
        path = args.root / rel
        if args.check:
            print(f"stale: {rel}")
        elif content is None:
            path.unlink()
            print(f"removed {rel}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if isinstance(content, bytes):
                path.write_bytes(content)
            else:
                path.write_text(content)
            print(f"wrote {rel}")
    if args.check and changes:
        print("Run `uv run task sync` to update them.", file=sys.stderr)
        return 1
    if not changes:
        print("the brand copies are in sync")
    return 0


if __name__ == "__main__":
    sys.exit(main())
