def problems(m: dict, root: Path) -> list[str]:
    """What is wrong with the brand: missing or undersized images, unreadable colours, and
    brand pages that would overwrite a template page."""
    found = []
    for key in REQUIRED_IMAGES:
        if key not in m["images"]:
            found.append(f"[images] {key} is required")
    for key, path in m["images"].items():
        if not path.exists():
            found.append(f"[images] {key}: {path} does not exist")
            continue
        if key in ("hero", "crest") and not m["alt"][key]:
            found.append(f"[images] {key}_alt is required when {key} is set")
        size, rule = png_size(path), PNG_SIZES.get(key)
        if rule and size:
            width, height, exact = rule
            if (size != (width, height)) if exact else (size[0] < width or size[1] < height):
                need = "exactly" if exact else "at least"
                found.append(f"[images] {key}: {size[0]}x{size[1]}, needs {need} {width}x{height}")
        elif rule and path.suffix.lower() != ".svg":
            found.append(f"[images] {key}: {path.name} must be a PNG or SVG")
    unknown = set(m["image_keys"]) - set(IMAGE_KEYS) - {f"{k}_alt" for k in IMAGE_KEYS}
    found += [f"[images] unknown key {key!r}" for key in sorted(unknown)]

    p = m["palette"]
    # The app colours need no check: contrast_for() picks black or white text, and the better
    # of the two always clears 4.5:1.
    pairs = [  # (what, foreground, background): WCAG AA for normal text is 4.5
        ("[theme.docs] accent on background", p["accent"], p["background"]),
        ("[theme.docs] text on background", p["text"], p["background"]),
        ("[theme.docs] accent_ink on white", p["accent_ink"], "#ffffff"),
        ("[theme.docs] accent_2_ink on white", p["accent_2_ink"], "#ffffff"),
    ]
    for what, fg, bg in pairs:
        if (ratio := contrast_ratio(fg, bg)) < 4.5:
            found.append(f"{what}: contrast {ratio:.1f}:1, needs 4.5:1 ({fg} on {bg})")

    for rel in outputs(m).keys() - OUTPUTS.keys():
        page = root / rel
        if page.exists() and NOTE not in page.read_text():
            found.append(f"brand/docs: {rel.name} would overwrite the template page {rel}")
    return found


