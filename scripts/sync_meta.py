"""Copy project identity (project.toml) and the brand theme (site.json) into the files that
cannot read them: the Zensical config, the mobile app, the compose variables, the npm metadata
and the README.

    uv run task sync                                # rewrite whatever is stale
    uv run python scripts/sync_meta.py --check      # exit 1 and list them instead

Standard library only and idempotent, so pre-commit and the unit tests can run it. Whole
generated files carry a GENERATED note; in hand-written files only the lines between
`sync:<name>` and `/sync:<name>` markers are replaced. See docs/content/site-manifest.md.
"""

import argparse
import json
import math
import re
import sys
import tomllib
from collections.abc import Callable
from pathlib import Path

NOTE = "GENERATED by scripts/sync_meta.py from project.toml and site.json. Edit those, then run `uv run task sync`."  # noqa: E501
MOBILE = Path("mobile")


# ---------------------------------------------------------------- inputs


def load(root: Path) -> dict:
    """project.toml plus the version, and the brand and theme from the bundled site.json."""
    meta = tomllib.loads((root / "project.toml").read_text())
    pyproject = tomllib.loads((root / "pyproject.toml").read_text())
    (site_file,) = root.glob("src/*/content/site.json")
    site = json.loads(site_file.read_text())
    project, org = meta["project"], meta["organisation"]
    brand = {
        # The same defaults as app.content.load_site.
        "name": site["brand"].get("name") or project["name"],
        "tagline": site["brand"]["tagline"],
        "collective": site["brand"].get("collective") or org["name"],
        "collective_url": site["brand"].get("collective_url"),
    }
    return {**meta, "version": pyproject["project"]["version"], "brand": brand, **site["theme"]}


# ---------------------------------------------------------------- helpers


def toml_str(value: str) -> str:
    """A TOML basic string; JSON string escapes are valid TOML."""
    return json.dumps(value, ensure_ascii=False)


def json_text(data: object) -> str:
    """The layout npm writes: two-space indent, trailing newline."""
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def splice(text: str, name: str, body: str, comment: tuple[str, str] = ("# ", "")) -> str:
    """Replace the lines between the `sync:<name>` and `/sync:<name>` marker lines."""
    start, end = (f"{comment[0]}{tag}sync:{name}{comment[1]}" for tag in ("", "/"))
    pattern = re.compile(rf"^({re.escape(start)}\n).*?^({re.escape(end)})$", re.M | re.S)
    if not pattern.search(text):
        raise ValueError(f"missing {start!r} ... {end!r} markers")
    return pattern.sub(lambda m: m[1] + body + m[2], text, count=1)


def hex_to_rgb(hex_colour: str) -> list[int]:
    n = int(hex_colour[1:], 16)
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255]


def mix(rgb: list[int], toward: int, weight: float) -> str:
    """Hex of `rgb` moved `weight` of the way to black (0) or white (255), rounded like JS."""
    return "#" + "".join(f"{math.floor(v + (toward - v) * weight + 0.5):02x}" for v in rgb)


def contrast_for(hex_colour: str) -> str:
    """White or black text, whichever reads better (WCAG relative luminance)."""
    r, g, b = (
        c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
        for c in (v / 255 for v in hex_to_rgb(hex_colour))
    )
    return "#000000" if 0.2126 * r + 0.7152 * g + 0.0722 * b > 0.179 else "#ffffff"


def ion_colour(name: str, hex_colour: str) -> dict[str, str]:
    """Ionic's colour variable set; the same maths as mobile/src/app/core/theme.ts."""
    rgb, contrast = hex_to_rgb(hex_colour), contrast_for(hex_colour)
    return {
        f"--ion-color-{name}": hex_colour,
        f"--ion-color-{name}-rgb": ", ".join(map(str, rgb)),
        f"--ion-color-{name}-contrast": contrast,
        f"--ion-color-{name}-contrast-rgb": ", ".join(map(str, hex_to_rgb(contrast))),
        f"--ion-color-{name}-shade": mix(rgb, 0, 0.12),
        f"--ion-color-{name}-tint": mix(rgb, 255, 0.1),
    }


def repo_slug(m: dict) -> str:
    return f"{m['repository']['owner']}/{m['repository']['name']}"


# ---------------------------------------------------------------- outputs
# Each takes the inputs and the file's current text (None if missing) and returns the new text.


def zensical(m: dict, text: str | None) -> str:
    project, org = m["project"], m["organisation"]
    footer = " · ".join(filter(None, [f"© {project['year']} {org['name']}", org.get("motto")]))
    text = splice(
        text or "",
        "identity",
        f"site_name = {toml_str(project['name'])}\n"
        f"site_description = {toml_str(project['description'])}\n"
        f"site_author = {toml_str(org['name'])}\n"
        f"copyright = {toml_str(footer)}\n",
    )
    social = ""
    if url := org.get("url"):
        social = (
            "[[project.extra.social]]\n"
            'icon = "lucide/globe"\n'
            f"link = {toml_str(url)}\n"
            f"name = {toml_str(org['name'])}\n"
        )
    return splice(text, "social", social)


def brand_scss(m: dict, _: str | None) -> str:
    lines = [
        f"// {NOTE}",
        "// First-paint brand colours; GET /site replaces them at runtime (app/core/theme.ts).",
        ":root {",
    ]
    for name in ("primary", "secondary", "tertiary"):
        lines += [f"  {key}: {value};" for key, value in ion_colour(name, m[name]).items()]
        lines.append("")
    return "\n".join(lines[:-1]) + "\n}\n"


def mobile_meta(m: dict, _: str | None) -> str:
    theme = {key: m[key] for key in ("primary", "secondary", "tertiary")}
    if "font_family" in m:
        theme["font_family"] = m["font_family"]
    return json_text(
        {
            "_generated": NOTE,
            "name": m["project"]["name"],
            "slug": m["project"]["slug"],
            "version": m["version"],
            "appId": m["mobile"]["app_id"],
            "brand": m["brand"],
            "theme": theme,
        }
    )


def env_project(m: dict, _: str | None) -> str:
    slug = m["project"]["slug"]
    return (
        f"# {NOTE}\n"
        "# Project identity for docker compose, loaded before .env.test or .env.production.\n"
        f"PROJECT_SLUG={slug}\n"
        f"COMPOSE_PROJECT_NAME={slug}\n"
        "# Images built locally\n"
        f"IMAGE_PREFIX={slug}\n"
        "# Images published by the release workflow (lower-case)\n"
        f"RELEASE_IMAGE_PREFIX=ghcr.io/{repo_slug(m).lower()}\n"
    )


