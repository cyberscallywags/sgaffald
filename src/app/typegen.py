"""Generate the mobile app's TypeScript types from the API's Pydantic models (their JSON
schemas), so the models are the only place a field is declared.

    uv run task types                        # write mobile/src/app/core/api.types.ts
    uv run python -m app.typegen --check     # exit 1 if it is stale (pre-commit, unit test)

A field is optional (`name?: T | null`) when the API may leave it null; a field with any other
default is always present in responses, so it is required.
"""

import argparse
import sys
from pathlib import Path

from pydantic.json_schema import models_json_schema

from app.docgen import documented_models

OUT = Path("mobile/src/app/core/api.types.ts")
HEADER = (
    "// GENERATED by `uv run task types` (app.typegen) from the API's Pydantic models.\n"
    "// Edit src/app/models.py, not this file.\n"
)
SCALARS = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}


def ts_type(schema: dict) -> str:
    if ref := schema.get("$ref"):
        return ref.rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(f"'{value}'" for value in schema["enum"])
    if "const" in schema:
        return f"'{schema['const']}'"
    if options := schema.get("anyOf"):
        return " | ".join(dict.fromkeys(ts_type(option) for option in options))
    kind = schema.get("type")
    if kind == "array":
        item = ts_type(schema.get("items", {}))
        return f"({item})[]" if " | " in item else f"{item}[]"
    if kind == "null":
        return "null"
    if kind == "object":
        return "Record<string, unknown>"
    return SCALARS.get(kind, "unknown")


def doc(text: str | None, indent: str = "") -> str:
    if not text:
        return ""
    lines = " ".join(text.split())
    return f"{indent}/** {lines} */\n"


def interface(name: str, schema: dict) -> str:
    required = set(schema.get("required", []))
    out = [doc(schema.get("description")), f"export interface {name} {{\n"]
    for field, prop in schema.get("properties", {}).items():
        optional = field not in required and prop.get("default", "") is None
        mark = "?" if optional else ""
        out.append(doc(prop.get("description"), "  "))
        out.append(f"  {field}{mark}: {ts_type(prop)};\n")
    out.append("}\n")
    return "".join(out)


def render() -> str:
    """Validation-mode schemas: they keep `default: null`, which marks the optional fields."""
    models = documented_models()
    _, schema = models_json_schema(
        [(cls, "validation") for cls in models], ref_template="#/$defs/{model}"
    )
    defs = schema["$defs"]
    return HEADER + "".join(f"\n{interface(cls.__name__, defs[cls.__name__])}" for cls in models)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is stale")
    parser.add_argument("--root", type=Path, default=Path("."), help="repository root")
    args = parser.parse_args(argv)
    path = args.root / OUT
    text = render()
    if path.exists() and path.read_text() == text:
        print(f"{OUT} is current")
        return 0
    if args.check:
        print(f"stale: {OUT}. Run `uv run task types`.", file=sys.stderr)
        return 1
    path.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
