"""Generate the documentation's reference pages from the code, so they cannot drift.

Run ``uv run python -m app.docgen`` to write the pages into ``docs/content/reference``.

Sources: the API's OpenAPI schema, the Pydantic models, Settings, the .env files, the
taskipy tasks in pyproject.toml and the brand in brand/brand.toml. The output is plain
Markdown (tables, code fences, links) that both Sphinx (MyST) and Zensical render, so one
generator feeds both sites.
"""

import argparse
import importlib.util
import json
import tomllib
from collections.abc import Iterable
from pathlib import Path
from typing import Any

from pydantic import BaseModel, SecretStr

from app import models
from app.config import Settings
from app.meta import load_meta

GENERATED = "<!-- Generated by `python -m app.docgen`. Edit the code, not this file. -->\n\n"
SECRET_WORDS = ("PASSWORD", "KEY", "SECRET", "TOKEN")
BASE_URL = "http://localhost:8000"


# ---------------------------------------------------------------- helpers


def cell(value: object) -> str:
    """Make a value safe inside a Markdown table cell."""
    text = "" if value is None else str(value)
    return text.replace("|", "\\|").replace("\n", " ").strip()


def table(headers: list[str], rows: Iterable[list[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def anchor(name: str) -> str:
    """Heading slug used by both MyST (myst_heading_anchors) and Zensical's toc."""
    return name.lower()


def documented_models() -> list[type[BaseModel]]:
    """The Pydantic models defined in app.models, in source order."""
    return [
        obj
        for obj in vars(models).values()
        if isinstance(obj, type)
        and issubclass(obj, BaseModel)
        and obj.__module__ == models.__name__
    ]


def model_link(name: str, page: str = "models.md") -> str:
    """Link to a model's section on the models page; framework schemas (e.g. FastAPI's
    HTTPValidationError) have no section there, so they stay plain code."""
    if name not in {cls.__name__ for cls in documented_models()}:
        return f"`{name}`"
    return f"[{name}]({page}#{anchor(name)})"


def schema_type(prop: dict[str, Any], page: str = "models.md") -> str:
    """A readable type for one JSON-schema property: `string`, `list of Item`, `int | null`."""
    if ref := prop.get("$ref"):
        return model_link(ref.rsplit("/", 1)[-1], page)
    if "enum" in prop:
        return " \\| ".join(f"`{v}`" for v in prop["enum"])
    if "const" in prop:
        return f"`{prop['const']}`"
    if options := prop.get("anyOf"):
        return " \\| ".join(schema_type(o, page) for o in options)
    kind = prop.get("type", "any")
    if kind == "array":
        return f"list of {schema_type(prop.get('items', {}), page)}"
    if fmt := prop.get("format"):
        return f"{kind} ({fmt})"
    return kind


def constraints(prop: dict[str, Any]) -> str:
    names = {
        "minLength": "min length",
        "maxLength": "max length",
        "pattern": "pattern",
        "minimum": "min",
        "maximum": "max",
    }
    parts = [f"{label} `{prop[key]}`" for key, label in names.items() if key in prop]
    return ", ".join(parts)


def example_for(schema: dict[str, Any]) -> dict[str, Any]:
    """Request-body example built from the field `examples` declared in models.py."""
    return {
        name: (prop.get("examples") or ["…"])[0]
        for name, prop in schema.get("properties", {}).items()
        if name in schema.get("required", [])
    }


# ---------------------------------------------------------------- pages


def models_page() -> str:
    classes = documented_models()
    out = [
        "# Data models\n\n",
        GENERATED,
        "The Pydantic models in `src/app/models.py` are the contract between the API, "
        "the web UI, the mobile app (`core/api.service.ts` mirrors them) and the tests.\n\n",
    ]
    for cls in classes:
        schema = cls.model_json_schema()
        required = set(schema.get("required", []))
        out.append(f"## {cls.__name__}\n\n")
        if doc := (cls.__doc__ or "").strip():
            out.append(f"{doc}\n\n")
        rows = []
        for name, prop in schema.get("properties", {}).items():
            default = prop.get("default")
            rows.append(
                [
                    f"`{name}`",
                    schema_type(prop),
                    "yes" if name in required else "no",
                    "" if default in (None, [], {}) else f"`{json.dumps(default)}`",
                    constraints(prop),
                ]
            )
        out.append(table(["Field", "Type", "Required", "Default", "Constraints"], rows))
        out.append("\n")
    return "".join(out)


def http_api_page(openapi: dict[str, Any]) -> str:
    info = openapi.get("info", {})
    out = [
        "# HTTP API\n\n",
        GENERATED,
        f"{info.get('description', '')}\n\n",
        f"Version `{info.get('version', '')}`. The running API also serves an interactive "
        f"Swagger UI at `{BASE_URL}/docs` and the raw schema at `{BASE_URL}/openapi.json`. "
        "Through the mobile container the same paths sit under `/api` "
        "(`http://localhost:8100/api/health`).\n\n",
    ]
    summary = []
    for path, methods in openapi.get("paths", {}).items():
        for method, op in methods.items():
            summary.append([f"`{method.upper()}`", f"`{path}`", op.get("summary", "")])
    out.append(table(["Method", "Path", "Summary"], summary))
    out.append("\n")

    schemas = openapi.get("components", {}).get("schemas", {})
    for path, methods in openapi.get("paths", {}).items():
        for method, op in methods.items():
            out.append(f"## {method.upper()} {path}\n\n")
            if desc := op.get("description"):
                out.append(f"{desc}\n\n")
            if tags := op.get("tags"):
                out.append(f"Tags: {', '.join(f'`{t}`' for t in tags)}\n\n")

            if params := op.get("parameters"):
                rows = [
                    [
                        f"`{p['name']}`",
                        p.get("in", ""),
                        schema_type(p.get("schema", {})),
                        "yes" if p.get("required") else "no",
                        f"`{p['schema']['default']}`" if "default" in p.get("schema", {}) else "",
                    ]
                    for p in params
                ]
                out.append("**Parameters**\n\n")
                out.append(table(["Name", "In", "Type", "Required", "Default"], rows))
                out.append("\n")

            body_ref = (
                op.get("requestBody", {})
                .get("content", {})
                .get("application/json", {})
                .get("schema", {})
                .get("$ref")
            )
            curl = f"curl -s -X {method.upper()} {BASE_URL}{path}"
            if body_ref:
                name = body_ref.rsplit("/", 1)[-1]
                out.append(f"**Request body**: {model_link(name)}\n\n")
                body = json.dumps(example_for(schemas.get(name, {})))
                curl += f" \\\n  -H 'Content-Type: application/json' \\\n  -d '{body}'"

            rows = []
            for status, resp in op.get("responses", {}).items():
                schema = resp.get("content", {}).get("application/json", {}).get("schema", {})
                rows.append([f"`{status}`", resp.get("description", ""), schema_type(schema)])
            out.append("**Responses**\n\n")
            out.append(table(["Status", "Description", "Body"], rows))
            out.append(f"\n```bash\n{curl}\n```\n\n")
    return "".join(out)


def read_env_file(path: Path) -> dict[str, tuple[str, str]]:
    """KEY -> (value, comment lines directly above it). The file's opening comment block
    describes the whole file, so it is not attached to the first variable."""
    entries: dict[str, tuple[str, str]] = {}
    comments: list[str] = []
    if not path.exists():
        return entries
    for raw in path.read_text().splitlines():
        line = raw.strip()
        if line.startswith("#"):
            comments.append(line.lstrip("# "))
        elif "=" in line:
            key, value = line.split("=", 1)
            entries[key.strip()] = (value.strip(), " ".join(comments) if entries else "")
            comments = []
        else:
            comments = []
    return entries


def mask(key: str, value: str) -> str:
    if not value:
        return ""
    return "(set)" if any(word in key for word in SECRET_WORDS) else f"`{value}`"


def configuration_page(root: Path) -> str:
    out = [
        "# Configuration\n\n",
        GENERATED,
        "## Service settings\n\n",
        "Every Python service reads these environment variables through "
        "`app.config.Settings`. Names are case-insensitive.\n\n",
    ]
    rows = []
    for name, field in Settings.model_fields.items():
        default = field.default
        if isinstance(default, SecretStr):
            shown = "(secret)"
        elif default in (None, [], ""):
            shown = ""
        else:
            shown = f"`{json.dumps(default) if isinstance(default, list) else default}`"
        rows.append([f"`{name.upper()}`", shown, field.description or ""])
    out.append(table(["Variable", "Default", "Description"], rows))

    project = read_env_file(root / ".env.project")
    test = read_env_file(root / ".env.test")
    prod = read_env_file(root / ".env.production.example")
    out.append(
        "\n## Environment files\n\n"
        "Docker compose reads `.env.project` first: the project identity, generated from "
        "`brand/brand.toml` by `uv run task sync`. Later files can use its values, as in "
        "`${PROJECT_SLUG}`.\n\n"
    )
    out.append(
        table(
            ["Variable", ".env.project", "Notes"],
            [[f"`{k}`", f"`{v}`", n] for k, (v, n) in project.items()],
        )
    )
    out.append(
        "\nThen one environment file. `.env.test` is committed with throwaway values; "
        "copy `.env.production.example` to `.env.production` (git-ignored) for real "
        "deployments. Secret values are hidden here.\n\n"
    )
    rows = []
    for key in dict.fromkeys([*test, *prod]):
        test_value, test_note = test.get(key, ("", ""))
        prod_value, prod_note = prod.get(key, ("", ""))
        rows.append(
            [f"`{key}`", mask(key, test_value), mask(key, prod_value), prod_note or test_note]
        )
    out.append(table(["Variable", ".env.test", ".env.production.example", "Notes"], rows))
    return "".join(out)


def tasks_page(root: Path) -> str:
    pyproject = tomllib.loads((root / "pyproject.toml").read_text())
    tool = pyproject.get("tool", {}).get("taskipy", {})
    variables = tool.get("variables", {})
    rows = []
    for name, task in tool.get("tasks", {}).items():
        cmd, help_text = (task, "") if isinstance(task, str) else (task["cmd"], task.get("help"))
        for var, value in variables.items():
            cmd = cmd.replace(f"{{{var}}}", value)
        rows.append([f"`{name}`", help_text, f"`{cmd}`"])
    return "".join(
        [
            "# Tasks\n\n",
            GENERATED,
            "Run any of these with `uv run task <name>`; `uv run task --list` prints the same "
            "list. They are defined under `[tool.taskipy.tasks]` in `pyproject.toml`.\n\n",
            table(["Task", "What it does", "Command"], rows),
        ]
    )


def site_sample_page(root: Path) -> str:
    return "".join(
        [
            "# Sample site manifest\n\n",
            GENERATED,
            "The bundled `brand/content/site.json`, validated by "
            f"{model_link('Site')} once `GET /site` has added the theme from `brand.toml`. "
            "Edit it in place, or copy the whole `brand/` folder and point `BRAND_DIR` at the "
            "copy.\n\n",
            "```json\n",
            (root / "brand/content/site.json").read_text().strip(),
            "\n```\n",
        ]
    )


def sync_outputs(root: Path) -> list[str]:
    """The files scripts/sync_meta.py keeps in step (it is a script, not part of the package)."""
    spec = importlib.util.spec_from_file_location("sync_meta", root / "scripts/sync_meta.py")
    if spec is None or spec.loader is None:
        return []
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return [path.as_posix() for path in module.output_paths(root)]


def project_metadata_page(root: Path) -> str:
    meta = load_meta(root / "brand/brand.toml")
    rows = [
        ["`project.name`", meta.name, "Titles, app name, docs"],
        ["`project.slug`", f"`{meta.slug}`", "Compose project, image names, cache keys"],
        ["`project.description`", meta.description, "Docs and package description"],
        ["`project.year`", meta.year, "Copyright notices"],
        ["`organisation.name`", meta.organisation.name, "Author, footers, default collective"],
        ["`organisation.url`", meta.organisation.url, "Docs portal social link"],
        ["`organisation.motto`", meta.organisation.motto, "Docs footers"],
        ["`repository.owner` / `name`", meta.repository.url, "README badges"],
        ["(derived)", f"`{meta.repository.image_prefix}`", "Release image prefix"],
        ["`mobile.app_id`", f"`{meta.mobile.app_id}`", "Capacitor app id"],
        [
            "`theme.primary` / `secondary` / `tertiary`",
            f"`{meta.theme.primary}` `{meta.theme.secondary}` `{meta.theme.tertiary}`",
            "Web UI and mobile colours, served by `GET /site`",
        ],
        ["version (`pyproject.toml`)", f"`{meta.version}`", "API, manual, mobile package"],
    ]
    copies = "".join(f"- `{path}`\n" for path in sync_outputs(root))
    return "".join(
        [
            "# Project metadata\n\n",
            GENERATED,
            "The project's identity and theme, from `brand/brand.toml` (read by `app.meta`), "
            "and its version, from `pyproject.toml`. Images, the docs palette and the brand's "
            "docs pages are described in the [brand kit](../guides/brand-kit.md); pages and "
            "copy are the [site manifest](../site-manifest.md)'s job.\n\n",
            table(["Key", "Value", "Used for"], rows),
            "\n## Generated copies\n\n"
            "The Python services and the Sphinx manual read `brand.toml` directly. These files "
            "cannot, so `uv run task sync` writes the values into them, and "
            "`tests/unit/test_sync.py` fails if any is stale:\n\n",
            copies,
        ]
    )


def generate(out_dir: Path, root: Path) -> list[Path]:
    from app.api.main import app

    pages = {
        "http-api.md": http_api_page(app.openapi()),
        "models.md": models_page(),
        "configuration.md": configuration_page(root),
        "tasks.md": tasks_page(root),
        "site-sample.md": site_sample_page(root),
        "project-metadata.md": project_metadata_page(root),
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in pages.items():
        path = out_dir / name
        path.write_text(text)
        written.append(path)
    return written


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=Path("docs/content/reference"))
    parser.add_argument("--root", type=Path, default=Path("."), help="repository root")
    args = parser.parse_args(argv)
    for path in generate(args.out, args.root):
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
