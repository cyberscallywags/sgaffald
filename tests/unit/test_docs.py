# ---------------------------------------------------------------- both sites list every page


def content_pages() -> set[str]:
    return {
        p.relative_to(CONTENT).as_posix()
        for p in CONTENT.rglob("*.md")
        if not (p.parent.name == "reference" and p.name in GENERATED)
    } | {f"reference/{name}" for name in GENERATED}


def zensical_nav() -> set[str]:
    config = tomllib.loads((DOCS / "zensical.toml").read_text())["project"]

    def walk(entries) -> set[str]:
        found: set[str] = set()
        for entry in entries:
            if isinstance(entry, str):
                found.add(entry)
            elif isinstance(entry, dict):
                for value in entry.values():
                    found |= walk(value) if isinstance(value, list) else walk([value])
        return found

    return {p for p in walk(config["nav"]) if p.endswith(".md")}


def sphinx_toctree() -> set[str]:
    manual = (CONTENT / "manual.md").read_text()
    blocks = re.findall(r"```\{toctree\}\n(.*?)```", manual, re.S)
    entries = {
        f"{line.strip()}.md"
        for block in blocks
        for line in block.splitlines()
        if line.strip() and not line.startswith(":")
    }
    return entries | {"manual.md"}


def test_every_page_is_in_the_portal_nav():
    assert zensical_nav() == content_pages() - SPHINX_ONLY


def test_every_page_is_in_the_manual_toctree():
    assert sphinx_toctree() == content_pages() - ZENSICAL_ONLY


def test_every_referenced_image_exists():
    pattern = re.compile(r"(?:\]\(|src=\"|srcset=\"|```\{image\} )([^)\"\s]+\.(?:png|webp|svg))")
    inline_code = re.compile(r"(?<!`)`[^`\n]+`(?!`)")  # examples in prose, not references
    for page in CONTENT.rglob("*.md"):
        for ref in pattern.findall(inline_code.sub("", page.read_text())):
            assert (page.parent / ref).resolve().exists(), f"{page.name}: {ref}"
